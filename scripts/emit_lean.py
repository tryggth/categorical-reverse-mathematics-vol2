#!/usr/bin/env python3
"""Emit Lean 4 modules from DuckDB + node TOMLs with line-level source maps."""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

import duckdb

REPO_ROOT = Path(__file__).resolve().parent.parent
DB_PATH = REPO_ROOT / "build" / "vol2.duckdb"
SOURCEMAPS_DIR = REPO_ROOT / "build" / "sourcemaps"
VOL2_LEAN_DIR = REPO_ROOT / "mathlib_vol2" / "HomotopyCRM" / "Vol2"

DIAG_RE_LAKE = re.compile(r"^(error|warning|info):\s*([^\s:]+\.lean):(\d+):(\d+):\s*(.*)$")
DIAG_RE_LEAN = re.compile(r"^([^\s:]+\.lean):(\d+):(\d+):\s*(error|warning|info):\s*(.*)$")


def render_node_block(node: dict[str, Any], spec_hash: str, body_hash: str) -> str:
    """Render one Mathlib Vol2 node block deterministically (shared with harvest_body.py)."""
    nid = node["id"]
    mathlib_spec = node["spec"]["mathlib"]
    signature = mathlib_spec["lean_signature"].rstrip()
    lean_body = node.get("body", {}).get("lean_body", "").rstrip()

    if "{{LEAN_BODY}}" in signature:
        body_wrapped = (
            f"-- BEGIN_BODY {nid}\n"
            f"{lean_body}\n"
            f"-- END_BODY {nid}"
        )
        rendered = signature.replace("{{LEAN_BODY}}", body_wrapped)
    else:
        rendered = signature

    guard_stanzas = mathlib_spec.get("guard_axiom_stanzas", [])
    guard_text = ""
    if guard_stanzas:
        guard_text = "\n\n" + "\n\n".join(s.rstrip() for s in guard_stanzas)

    return (
        f"-- BEGIN_NODE {nid} [spec:{spec_hash[:8]} body:{body_hash[:8]}]\n"
        f"{rendered}{guard_text}\n"
        f"-- END_NODE {nid}\n"
    )


def topo_sort_module_nodes(
    module_nodes: list[dict[str, Any]], lean_edges: list[tuple[str, str]]
) -> list[dict[str, Any]]:
    ids = {n["id"] for n in module_nodes}
    by_id = {n["id"]: n for n in module_nodes}
    indeg: dict[str, int] = {nid: 0 for nid in ids}
    adj: dict[str, list[str]] = {nid: [] for nid in ids}
    for src, dst in lean_edges:
        if src in ids and dst in ids:
            adj[src].append(dst)
            indeg[dst] += 1
    queue = sorted([nid for nid, d in indeg.items() if d == 0])
    ordered: list[dict[str, Any]] = []
    while queue:
        curr = queue.pop(0)
        ordered.append(by_id[curr])
        for nxt in sorted(adj[curr]):
            indeg[nxt] -= 1
            if indeg[nxt] == 0:
                queue.append(nxt)
        queue.sort()
    if len(ordered) != len(module_nodes):
        raise RuntimeError("Cycle detected while topologically sorting module nodes.")
    return ordered


def emit_mathlib_modules(con: duckdb.DuckDBPyConnection) -> list[str]:
    rows = con.execute(
        "SELECT id, module, spec_hash, body_hash, file_path, raw_json FROM nodes WHERE formal_pkg = 'mathlib_vol2'"
    ).fetchall()
    lean_edges = con.execute(
        "SELECT src_id, dst_id FROM edges WHERE fiber = 'lean_dep'"
    ).fetchall()

    by_module: dict[str, list[dict[str, Any]]] = {}
    hashes: dict[str, tuple[str, str, str]] = {}
    for nid, module, spec_h, body_h, file_path, raw_json in rows:
        data = json.loads(raw_json)
        by_module.setdefault(module, []).append(data)
        hashes[nid] = (spec_h, body_h, file_path)

    VOL2_LEAN_DIR.mkdir(parents=True, exist_ok=True)
    SOURCEMAPS_DIR.mkdir(parents=True, exist_ok=True)

    emitted_modules: list[str] = []
    for mod_name in sorted(by_module.keys()):
        if not mod_name.startswith("HomotopyCRM.Vol2."):
            raise ValueError(f"Expected module under HomotopyCRM.Vol2.*, got {mod_name}")
        short_name = mod_name[len("HomotopyCRM.Vol2.") :]
        ordered = topo_sort_module_nodes(by_module[mod_name], lean_edges)

        imports: list[str] = []
        seen_imp: set[str] = set()
        for n in ordered:
            for imp in n["spec"]["mathlib"].get("imports", []):
                if imp not in seen_imp:
                    seen_imp.add(imp)
                    imports.append(imp)

        lines: list[str] = [
            "/-",
            "AUTO-GENERATED BY scripts/emit_lean.py — DO NOT EDIT OUTSIDE `-- BEGIN_BODY` / `-- END_BODY`.",
            "-/",
            *[f"import {imp}" for imp in imports],
            "",
            "namespace HomotopyCRM.Vol2",
            "",
        ]
        intervals: list[dict[str, Any]] = []
        for n in ordered:
            nid = n["id"]
            spec_h, body_h, file_path = hashes[nid]
            block = render_node_block(n, spec_h, body_h)
            start_line = len(lines) + 1
            block_lines = block.splitlines()
            lines.extend(block_lines)
            end_line = len(lines)
            lines.append("")
            intervals.append(
                {
                    "node_id": nid,
                    "start_line": start_line,
                    "end_line": end_line,
                    "spec_hash": spec_h,
                    "body_hash": body_h,
                    "file_path": file_path,
                }
            )
        lines.append("end HomotopyCRM.Vol2")
        lines.append("")

        out_path = VOL2_LEAN_DIR / f"{short_name}.lean"
        out_path.write_text("\n".join(lines), encoding="utf-8")

        rel_lean_path = str(out_path.relative_to(REPO_ROOT))
        map_path = SOURCEMAPS_DIR / f"{short_name}.lean.map.json"
        map_path.write_text(
            json.dumps(
                {
                    "module": mod_name,
                    "lean_file": rel_lean_path,
                    "intervals": intervals,
                },
                indent=2,
            )
            + "\n",
            encoding="utf-8",
        )
        emitted_modules.append(mod_name)
    return emitted_modules


def emit_node_op_lean(node: dict[str, Any]) -> str:
    nid = node["id"]
    op = node["op"]
    args = node.get("args", [])
    mapping = {
        "UnivS": lambda a: f".univS {a[0]}",
        "UnivF": lambda a: f".univF {a[0]}",
        "BoolS": lambda _: ".boolS",
        "BoolF": lambda _: ".boolF",
        "TrueF": lambda _: ".trueF",
        "FalseF": lambda _: ".falseF",
        "Var": lambda a: f".var {a[0]}",
        "PiS": lambda a: f".piS {a[0]} {a[1]}",
        "PiF": lambda a: f".piF {a[0]} {a[1]}",
        "LamS": lambda a: f".lamS {a[0]} {a[1]}",
        "LamF": lambda a: f".lamF {a[0]} {a[1]}",
        "AppS": lambda a: f".appS {a[0]} {a[1]}",
        "AppF": lambda a: f".appF {a[0]} {a[1]}",
        "LiftFtoS": lambda a: f".liftFtoS {a[0]}",
        "InnerUnivalenceV": lambda a: f".innerUnivalence {a[0]}",
        "InnerCoalgebraNu": lambda a: f".innerCoalgebraNu {a[0]}",
        "OuterStrictEq": lambda a: f".outerStrictEq {a[0]} {a[1]}",
        "SmallnessReplacement": lambda a: f".smallnessReplacement {a[0]}",
    }
    return f"{{ id := {nid}, op := {mapping[op](args)} }}"


def lean_str_lit(s: str) -> str:
    escaped = s.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def lean_bool(b: bool) -> str:
    return "true" if b else "false"


def emit_cert_checks(con: duckdb.DuckDBPyConnection) -> str:
    rows = con.execute(
        "SELECT id, cert_path, spec_hash, body_hash, raw_json FROM nodes WHERE formal_pkg = 'kernel_arena' ORDER BY id"
    ).fetchall()
    lines: list[str] = [
        "/-",
        "AUTO-GENERATED BY scripts/emit_lean.py — Bridge proofs from KernelArena certificates into Vol II.",
        "-/",
        "import KernelArena",
        "",
        "namespace HomotopyCRM.Vol2",
        "",
    ]
    intervals: list[dict[str, Any]] = []
    for nid, cert_rel, spec_h, body_h, raw_json in rows:
        cert_data = json.loads((REPO_ROOT / cert_rel).read_text(encoding="utf-8"))
        data = json.loads(raw_json)
        ka_spec = data["spec"]["kernel_arena"]
        cert_const = ka_spec["cert_const_short"]
        thm_const = ka_spec["check_thm_short"]

        flags = cert_data["strata_flags"]
        dim_ctxs = ", ".join(lean_str_lit(c) for c in cert_data["dim_contexts"])
        nodes_lines = [f"    {emit_node_op_lean(n)}" for n in cert_data["nodes"]]
        start_line = len(lines) + 1
        lines.extend(
            [
                f"-- BEGIN_NODE {nid} [spec:{spec_h[:8]} body:{body_h[:8]}]",
                f"def {cert_const} : KernelArena.Cert where",
                f"  schema := {lean_str_lit(cert_data['schema'])}",
                f"  declName := {lean_str_lit(cert_data['decl_name'])}",
                f"  universeDepthK := {cert_data['universe_depth_k']}",
                f"  fuelHint := {cert_data['fuel_hint']}",
                f"  strataFlags := {{",
                f"    innerUnivalenceV := {lean_bool(flags['inner_univalence_V'])}",
                f"    innerCoalgebraNu := {lean_bool(flags['inner_coalgebra_nu'])}",
                f"    outerStrictEq := {lean_bool(flags['outer_strict_eq'])}",
                f"    smallnessReplacement := {lean_bool(flags['smallness_replacement'])}",
                f"  }}",
                f"  dimContexts := [{dim_ctxs}]",
                "  nodes := #[",
                ",\n".join(nodes_lines),
                "  ]",
                f"  goalTypeNode := {cert_data['goal_type_node']}",
                f"  proofTermNode := {cert_data['proof_term_node']}",
                f"  sha256Arena := {lean_str_lit(cert_data['sha256_arena'])}",
                "",
                f"theorem {thm_const} :",
                f"    KernelArena.Check.checkCert {cert_data['fuel_hint']} {cert_const} = true :=",
                "  rfl",
                "",
                "/-- info: "
                + f"'HomotopyCRM.Vol2.{thm_const}' does not depend on any axioms"
                + " -/",
                "#guard_msgs in",
                f"#print axioms {thm_const}",
                f"-- END_NODE {nid}",
                "",
            ]
        )
        end_line = len(lines) - 1
        intervals.append(
            {
                "node_id": nid,
                "start_line": start_line,
                "end_line": end_line,
                "spec_hash": spec_h,
                "body_hash": body_h,
            }
        )

    lines.append("end HomotopyCRM.Vol2")
    lines.append("")
    out_path = VOL2_LEAN_DIR / "CertChecks.lean"
    out_path.write_text("\n".join(lines), encoding="utf-8")
    (SOURCEMAPS_DIR / "CertChecks.lean.map.json").write_text(
        json.dumps(
            {
                "module": "HomotopyCRM.Vol2.CertChecks",
                "lean_file": str(out_path.relative_to(REPO_ROOT)),
                "intervals": intervals,
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    return "HomotopyCRM.Vol2.CertChecks"


def resolve_lean_error(filepath: str, line: int, col: int) -> dict[str, Any] | None:
    """Resolve a Lean file:line:col diagnostic back to its owning node_id via sourcemaps."""
    norm = filepath.replace("\\", "/")
    if norm.startswith(str(REPO_ROOT) + "/"):
        norm = norm[len(str(REPO_ROOT)) + 1 :]
    if norm.startswith("./"):
        norm = norm[2:]
    if not norm.startswith("mathlib_vol2/") and (REPO_ROOT / "mathlib_vol2" / norm).exists():
        norm = f"mathlib_vol2/{norm}"

    for map_file in sorted(SOURCEMAPS_DIR.glob("*.lean.map.json")):
        data = json.loads(map_file.read_text(encoding="utf-8"))
        if data.get("lean_file") == norm or norm.endswith("/" + data.get("lean_file", "")):
            for iv in data.get("intervals", []):
                if iv["start_line"] <= line <= iv["end_line"]:
                    return {
                        "node_id": iv["node_id"],
                        "file": norm,
                        "line": line,
                        "col": col,
                        "module": data.get("module"),
                    }
    return None


def parse_and_map_lean_diagnostics(log_text: str) -> list[dict[str, Any]]:
    mapped: list[dict[str, Any]] = []
    for raw_line in log_text.splitlines():
        s = raw_line.strip()
        m_lake = DIAG_RE_LAKE.match(s)
        if m_lake:
            sev, fp, ln_s, col_s, msg = m_lake.groups()
        else:
            m_lean = DIAG_RE_LEAN.match(s)
            if not m_lean:
                continue
            fp, ln_s, col_s, sev, msg = m_lean.groups()
        if sev not in ("error", "warning"):
            continue
        loc = resolve_lean_error(fp, int(ln_s), int(col_s))
        mapped.append(
            {
                "file": fp,
                "line": int(ln_s),
                "col": int(col_s),
                "severity": sev,
                "message": msg,
                "node_id": loc["node_id"] if loc else None,
            }
        )
    return mapped


def emit_all() -> list[str]:
    con = duckdb.connect(str(DB_PATH), read_only=True)
    mods = emit_mathlib_modules(con)
    cert_mod = emit_cert_checks(con)
    mods.append(cert_mod)
    con.close()

    all_lean = VOL2_LEAN_DIR / "All.lean"
    all_lean.write_text("".join(f"import {m}\n" for m in mods), encoding="utf-8")
    return mods


def main() -> int:
    mods = emit_all()
    print(f"EMIT_LEAN_OK modules={mods}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
